"""
30 质量门禁
=======

测试、类型检查、lint、格式、构建检查各自发现不同问题；门禁应快速、稳定、自动化。

门禁选择应来自项目风险：库关注兼容性和构建，服务还要关注配置与部署验证。
频繁误报或偶发失败会让团队忽视结果，因此规则必须可重复并有明确修复方式。
本地和 CI 应调用同一组底层命令，避免维护两套含义不同的检查流程。
高成本检查可以分层执行，但合并前的必需结果必须清楚且不可绕过。
当门禁失败时，应先修复原因；若规则已不适用，则通过评审修改规则和依据。
"""

gates={'tests':'行为正确','type-check':'静态类型契约','lint':'潜在错误/规则','format':'统一格式','build':'可构建','install-smoke':'产物可安装启动'}
for k,v in gates.items(): print(f'{k:14} -> {v}')
print('\n不要追求“工具越多越专业”；每个工具都应有明确价值。')
