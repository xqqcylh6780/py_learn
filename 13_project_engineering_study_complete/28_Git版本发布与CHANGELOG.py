"""
28 Git、版本与 CHANGELOG
====================

版本发布应能从 Git 历史追溯：明确 tag、变更说明、构建来源和回滚点。

版本号标识不可变产物，tag 连接源码，CHANGELOG 则解释使用者会感受到的变化。
三者不一致时，故障报告和依赖解析都会失去可靠依据。
回滚通常意味着发布一个明确的修复版本或恢复部署产物，而不是覆盖已经公开的版本。
"""

for x in ['版本号','Git commit/tag','发布时间','用户可见变更','破坏性变更与迁移说明','已知问题']:
    print('-',x)
print('\n不要发布后悄悄覆盖同一个版本号的包。')
print('CHANGELOG 写给使用者，不是把 git log 原样复制。')
