# -*- coding: utf-8 -*-
"""
01 从脚本到工程
=========

工程化不是目录变多，而是让项目能够稳定地安装、运行、测试、发布、部署和维护。

先从交付目标反推结构：库、CLI、服务和一次性脚本需要的工程设施并不相同。
目录只是约定的载体，真正的价值来自可重复命令、明确边界和自动验证。
常见误区是先复制一套庞大模板，再让项目长期背负没有使用者的配置。
"""

def show(title):
    print('\n' + '=' * 70)
    print(title)
    print('=' * 70)

show('一个工程至少回答 7 个问题')
for item in [
    '1. 用哪个 Python 版本？',
    '2. 依赖是什么，怎样安装？',
    '3. 源码放哪里，入口在哪里？',
    '4. 配置与秘密信息从哪里来？',
    '5. 怎样测试和做质量检查？',
    '6. 怎样构建 wheel/sdist？',
    '7. 怎样发布、部署、回滚？',
]:
    print(item)

show('推荐基础结构')
print('my_project/')
print('├─ pyproject.toml')
print('├─ README.md')
print('├─ src/my_project/')
print('└─ tests/')

show('工程化核心')
print('可重建：换机器能重新创建环境')
print('可验证：测试和质量检查可自动运行')
print('可交付：有明确安装包/镜像/可执行物')
print('可观察：日志、版本、错误码便于排错')
