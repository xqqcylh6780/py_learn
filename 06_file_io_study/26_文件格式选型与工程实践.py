"""26 文件格式与工程实践：最后把知识串起来。"""

def show(t): print('\n'+'='*68+'\n'+t+'\n'+'='*68)

show('1. 怎么选格式')
rows=[
('纯文本','日志/配置片段/人读内容','简单，但缺少结构'),
('CSV','二维表格','类型弱、嵌套差'),
('JSON','跨语言结构化数据','可读、生态好、类型有限'),
('pickle','可信 Python 内部对象','方便但不安全、不适合外部交换'),
('SQLite','结构化可查询数据','需要事务/查询时优于手搓多个文件'),
]
for r in rows: print(f'{r[0]:8} {r[1]:22} {r[2]}')

show('2. 工程检查表')
for x in [
'文本是否显式指定 encoding？',
'大文件是否流式处理？',
'覆盖关键文件是否采用临时文件 + replace？',
'输入路径是否可能目录穿越？',
'解压不可信归档是否验证条目路径？',
'是否错误加载不可信 pickle？',
'是否正确处理 FileNotFoundError/PermissionError？',
'跨平台 Windows/POSIX 行为是否验证？',
'是否需要哈希、备份、事务或文件锁？',
]: print('-',x)

show('3. 文件不是数据库')
print('当你开始需要复杂并发写、事务、查询、索引、约束时，应考虑 SQLite/数据库，而不是不断给 JSON 文件加锁。')
